/**
 * Markdown renderings of a results document: the assessment report, the blueprint, and one file per work packet
 * (written for a human or any coding agent). Every untrusted string is escaped; everything shown is read from the
 * results JSON, which stays the source of truth.
 */
import type { Finding, Results, WorkPacket } from "../types.js";
import { PILLARS } from "../types.js";
import { CONTROL_BY_ID } from "../validation/catalog.js";
import { TIER_INFO } from "../validation/tiers.js";
import { code, md } from "./escape.js";

/** Rendering options. */
export interface RenderOptions {
  branding: boolean;
}

const pct = (n: number): string => `${Math.round(n * 100)}%`;
const PILLAR_LABEL = { customer: "Customer", technology: "Technology", trust: "Trust" } as const;
const BRANDING =
  "Generated by Product Check, an EnWithAI Engineering Commons tool. JSON is the source of truth; this file is a rendering.";

/** One-line score text for a pillar. */
export function scoreText(r: Results, p: (typeof PILLARS)[number]): string {
  const s = r.scorecard.pillars[p];
  return s.score === null
    ? "not scored (insufficient evidence)"
    : `${s.score}/100${s.cap.applied ? ` (capped: ${s.cap.reason ?? ""})` : ""}`;
}

/** Findings that are still open (incl. carried-unverified), most severe first. */
const openFindings = (r: Results): Finding[] =>
  r.findings.filter((f) => f.status === "OPEN" || f.status === "UNVERIFIED");

/** The assessment report. */
export function renderReport(r: Results, options: RenderOptions): string {
  const lines: string[] = [];
  const v = r.verdict;
  lines.push(`# Product Check report: ${md(r.contract.target.name)}`, "");
  if (r.run.demo)
    lines.push(
      "> **DEMO DATA.** This assessment ran on a synthetic example application. It says nothing about any real product.",
      ""
    );
  if (r.run.status !== "COMPLETED")
    lines.push(`> **Run status: ${r.run.status}.** ${r.run.errors.map((e) => md(e)).join(" ")}`, "");
  lines.push(
    `**Verdict: ${v.verdict}** at ${v.tier} (${TIER_INFO[v.tier].name}), tier wording "${md(v.tier_alias)}".`,
    ""
  );
  for (const reason of v.reasons) lines.push(`- ${md(reason)}`);
  lines.push("", `_${md(v.bounded_by)}_`, "");
  lines.push("## Customer × Technology × Trust", "");
  lines.push(
    "Pillars are scored separately and never averaged. Untested controls lower coverage; they never count as passed.",
    ""
  );
  lines.push(
    "| Pillar | Score | Coverage | Confidence | Trend | Pass | Partial | Fail | Blocked | Not tested |"
  );
  lines.push("|---|---|---|---|---|---|---|---|---|---|");
  for (const p of PILLARS) {
    const s = r.scorecard.pillars[p];
    const trend =
      s.trend === null
        ? "—"
        : s.trend.delta === null
          ? "n/a"
          : `${s.trend.delta >= 0 ? "+" : ""}${s.trend.delta}`;
    lines.push(
      `| ${PILLAR_LABEL[p]} | ${scoreText(r, p)} | ${pct(s.coverage)} | ${s.confidence} | ${trend} | ${s.counts.PASS} | ${s.counts.PARTIAL} | ${s.counts.FAIL} | ${s.counts.BLOCKED} | ${s.counts.NOT_TESTED} |`
    );
  }
  const o = r.scorecard.open_findings;
  lines.push(
    "",
    `Open findings: P0 ${o.P0} · P1 ${o.P1} · P2 ${o.P2} · P3 ${o.P3} · accepted risks ${r.scorecard.accepted_risks} · overall coverage ${pct(r.scorecard.overall_coverage)}`,
    ""
  );
  lines.push("## Hard gates", "", "| Gate | Status | Controls |", "|---|---|---|");
  for (const g of r.scorecard.gates)
    lines.push(`| ${g.gate_id}: ${md(g.title)} | ${g.status} | ${g.control_ids.join(", ")} |`);
  lines.push(
    "",
    "## What was inspected (points of presence)",
    "",
    "| Point of presence | Status | Scope | Limitations |",
    "|---|---|---|---|"
  );
  for (const p of r.pop_coverage.pops)
    lines.push(
      `| ${md(p.name)} | ${p.status} | ${p.scope ? md(p.scope) : "—"} | ${p.limitations.map((l) => md(l)).join(" ") || "—"} |`
    );
  const open = openFindings(r);
  lines.push("", `## Open findings (${open.length})`, "");
  if (open.length === 0)
    lines.push("No open findings in the checked controls. Unchecked controls are listed below.");
  else {
    lines.push(
      "| ID | Severity | Pillar | Finding | Location | Basis | Lifecycle | Work packet |",
      "|---|---|---|---|---|---|---|---|"
    );
    for (const f of open) {
      lines.push(
        `| ${f.id} | ${f.severity}${f.ux_severity ? `/${f.ux_severity}` : ""} | ${PILLAR_LABEL[f.pillar]} | ${md(f.title, 200)} | ${code(f.location, 120)} | ${f.epistemic}, ${f.confidence.toLowerCase()} confidence | ${f.lifecycle}${f.status === "UNVERIFIED" ? " (not re-checked)" : ""} | ${f.work_packet_id ?? "—"} |`
      );
    }
  }
  const accepted = r.findings.filter((f) => f.status === "ACCEPTED_RISK");
  if (accepted.length > 0) {
    lines.push("", "### Accepted risks", "");
    for (const f of accepted) lines.push(`- ${f.id} ${f.severity} ${md(f.title)}`);
  }
  const resolved = r.findings.filter((f) => f.status === "RESOLVED");
  if (resolved.length > 0) {
    lines.push("", "### Verified fixes (resolved on retest)", "");
    for (const f of resolved) lines.push(`- ${f.id} ${md(f.title)} — verified in ${r.run.run_id}`);
  }
  lines.push("", "## Not verified: the next evidence to collect", "");
  const unchecked = r.validations.filter((x) => x.status === "BLOCKED" || x.status === "NOT_TESTED");
  if (unchecked.length === 0) lines.push("Every applicable control was checked.");
  for (const x of unchecked)
    lines.push(`- **${x.control_id}** ${md(x.title)} — ${x.status}: ${md(x.reason ?? "")}`);
  if (r.comparison) {
    const c = r.comparison;
    lines.push("", "## Retest comparison", "", `Baseline ${c.baseline_run_id}.`, "");
    lines.push(
      `- Score change: ${PILLARS.map((p) => `${PILLAR_LABEL[p]} ${c.score_delta[p] === null ? "n/a" : `${(c.score_delta[p] ?? 0) >= 0 ? "+" : ""}${c.score_delta[p] ?? 0}`}`).join(", ")}`
    );
    lines.push(
      `- Findings: ${c.findings_new.length} new, ${c.findings_resolved.length} resolved (verified), ${c.findings_reopened.length} reopened, ${c.findings_persisting.length} persisting, ${c.findings_unverified.length} not re-checked`
    );
    lines.push(
      `- Controls: ${c.improved_controls.length} improved${c.improved_controls.length ? ` (${c.improved_controls.join(", ")})` : ""}, ${c.regressed_controls.length} regressed${c.regressed_controls.length ? ` (${c.regressed_controls.join(", ")})` : ""}`
    );
  }
  if (r.limitations.length > 0) {
    lines.push("", "## Limitations", "");
    for (const l of r.limitations) lines.push(`- ${code(l.code)} (${l.count}): ${md(l.message)}`);
  }
  lines.push("", "## Run", "");
  lines.push(
    `Run ${r.run.run_id} · ${r.run.status} · mode ${r.run.mode_effective ?? "none"} (requested ${r.run.mode_requested}) · tiers ${r.run.tiers_applied.join(", ")} · Product Check ${r.run.tool_version.replace(/[^0-9A-Za-z.+-]/g, "")} · methodology CT3 (Customer × Technology × Trust, ${r.run.methodology.relationship}) · rubric ${r.scorecard.rubric_version} · network requests ${r.run.network.requests}`
  );
  lines.push(
    "",
    "Product Check reports evidence-bounded readiness. It is not a penetration test, a legal or compliance certification, or a guarantee of production readiness."
  );
  if (options.branding) lines.push("", `<sub>${BRANDING}</sub>`);
  return `${lines.join("\n")}\n`;
}

/** The blueprint document. */
export function renderBlueprint(r: Results, options: RenderOptions): string {
  const b = r.blueprint;
  const lines: string[] = [`# Engineering blueprint: ${md(r.contract.target.name)}`, ""];
  if (r.run.demo) lines.push("> **DEMO DATA.** Synthetic example application.", "");
  lines.push(
    "Advisory only: Product Check never changes code. A remediation becomes VERIFIED only when a retest observes the control passing.",
    ""
  );
  lines.push(
    "## As-is architecture (discovered)",
    "",
    "| Component | Category | Certainty |",
    "|---|---|---|"
  );
  for (const c of b.as_is.components) lines.push(`| ${code(c.name)} | ${c.category} | ${c.certainty} |`);
  if (b.as_is.components.length === 0) lines.push("| (none discovered) | — | — |");
  lines.push("", "### Stated uncertainties", "");
  for (const u of b.as_is.uncertainties) lines.push(`- ${md(u)}`);
  lines.push("", "## To-be architecture (target changes)", "");
  if (b.to_be.changes.length === 0) lines.push("No target changes: no open findings.");
  for (const c of b.to_be.changes) {
    lines.push(
      `- **${c.id}** ${md(c.statement)} _Why:_ ${md(c.rationale)}${c.alternatives.length ? ` _Alternatives:_ ${c.alternatives.map((a) => md(a)).join("; ")}` : ""} (findings: ${c.finding_ids.join(", ")})`
    );
  }
  lines.push(
    "",
    "## Remediation plan",
    "",
    "| Order | Remediation | Priority | Horizon | Effort | Depends on | Human review | Verification |",
    "|---|---|---|---|---|---|---|---|"
  );
  b.remediations.forEach((x, i) => {
    lines.push(
      `| ${i + 1} | ${x.id}: ${md(CONTROL_BY_ID.get(x.control_id)?.title ?? x.control_id)} | ${x.priority} | ${x.horizon} | ${x.effort ?? "—"} | ${x.depends_on.join(", ") || "—"} | ${x.human_review_required ? "yes" : "no"} | ${x.verification.status} |`
    );
  });
  for (const x of b.remediations) {
    lines.push(
      "",
      `### ${x.id} (${x.priority}, ${x.horizon})`,
      "",
      `**Problem.** ${md(x.problem)}`,
      "",
      `**Why it matters.** ${md(x.why_it_matters)}`,
      "",
      `**Recommended change.** ${md(x.recommended_change)}`,
      "",
      "**Acceptance criteria**",
      ""
    );
    for (const a of x.acceptance_criteria) lines.push(`- [ ] ${md(a)}`);
    lines.push("", `**Regression protection.** ${md(x.regression_test.description)}`);
    if (x.regression_test.candidate)
      lines.push(
        "",
        `Candidate (${md(x.regression_test.candidate.language)}):`,
        "",
        "```",
        x.regression_test.candidate.code.replace(/```/g, "ʼʼʼ"),
        "```"
      );
  }
  lines.push("", "## Target test architecture", "", "| Layer | Current | Target |", "|---|---|---|");
  for (const l of b.test_architecture.layers)
    lines.push(`| ${md(l.layer)} | ${l.current} | ${md(l.target)} |`);
  lines.push(
    "",
    "## Traceability",
    "",
    "| Finding | Requirement / journey | Observed | Root cause | Remediation | Retest |",
    "|---|---|---|---|---|---|"
  );
  for (const t of b.traceability)
    lines.push(
      `| ${t.finding_id} | ${md(t.journey_or_requirement, 160)} | ${md(t.observed_behavior, 160)} | ${md(t.root_cause, 120)} | ${t.remediation_id ?? "—"} | ${t.retest_outcome} |`
    );
  if (b.human_review.length > 0) {
    lines.push("", "## Human review required", "");
    for (const h of b.human_review) lines.push(`- ${md(h)}`);
  }
  if (options.branding) lines.push("", `<sub>${BRANDING}</sub>`);
  return `${lines.join("\n")}\n`;
}

/** One work packet, written so a human or any coding agent can act on it. */
export function renderPacket(r: Results, p: WorkPacket): string {
  const findings = r.findings.filter((f) => p.finding_ids.includes(f.id));
  const lines: string[] = [`# ${p.id}: ${md(p.title)}`, ""];
  if (r.run.demo) lines.push("> DEMO DATA: synthetic example application.", "");
  lines.push(
    `Status: **${p.status}** · Human approval required: **${p.human_approval_required ? "yes" : "no"}** · Source run: ${r.run.run_id}`,
    ""
  );
  lines.push("## Objective", "", md(p.objective), "", "## Findings", "");
  for (const f of findings)
    lines.push(`- ${f.id} (${f.severity}, ${f.epistemic}): ${md(f.actual, 400)} at ${code(f.location)}`);
  lines.push("", "## Where to look", "");
  for (const l of p.context.locations) lines.push(`- ${code(l)}`);
  lines.push("", "## Constraints", "");
  for (const c of p.constraints) lines.push(`- ${md(c)}`);
  lines.push("", "## Suggested steps", "");
  p.suggested_steps.forEach((s, i) => lines.push(`${i + 1}. ${md(s)}`));
  lines.push("", "## Acceptance criteria", "");
  for (const a of p.acceptance_criteria) lines.push(`- [ ] ${md(a)}`);
  lines.push(
    "",
    "## Verify",
    "",
    "```bash",
    p.verification_command,
    "```",
    "",
    "This packet is complete only when the retest reports the control PASS; a completion claim alone is not verification.",
    ""
  );
  return `${lines.join("\n")}`;
}
