/**
 * Generates "Vibe Notes", a SYNTHETIC vibe-coded Next.js-style app used by the Product Check demo, as its own git
 * repository in ./app (git-ignored by Product Check). Nothing here is a real product, and every credential-like
 * string is a deterministic fake assembled at generation time (so none is committed to this repository).
 *
 *   node create-app.mjs              baseline commit (deliberately weak)
 *   node create-app.mjs --remediate  second commit applying the blueprint's fixes
 *   --dir <path>                     generate somewhere else (used by tests)
 *
 * Commits use a fixed author and dates, so commit IDs are identical on every machine with git installed.
 */
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dirFlag = process.argv.indexOf("--dir");
const app = dirFlag > 0 ? process.argv[dirFlag + 1] : join(here, "app");
const remediate = process.argv.includes("--remediate");

const fake = (label, n) =>
  createHash("sha256")
    .update(`vibe-notes-demo:${label}`)
    .digest("hex")
    .replace(/[0-9]/g, (d) => "ABCDEFGHIJ"[Number(d)])
    .slice(0, n);
const b64 = (obj) => Buffer.from(JSON.stringify(obj)).toString("base64url");
const jwt = (role) =>
  [
    b64({ alg: "HS256", typ: "JWT" }),
    b64({ iss: "supabase-demo", role, ref: "vibenotesdemo" }),
    fake(`sig-${role}`, 43),
  ].join(".");
const STRIPE = ["sk", "live", `51${fake("stripe", 30)}`].join("_");
const DB_PASSWORD = fake("dbpass", 18);
const SERVICE_ROLE = jwt("service_role");
const ANON = jwt("anon");

function write(rel, text) {
  const path = join(app, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text.replace(/^\n/, ""));
}
function git(args, date) {
  const env = {
    ...process.env,
    GIT_AUTHOR_NAME: "Demo Author",
    GIT_AUTHOR_EMAIL: "demo@example.invalid",
    GIT_COMMITTER_NAME: "Demo Author",
    GIT_COMMITTER_EMAIL: "demo@example.invalid",
    GIT_AUTHOR_DATE: date,
    GIT_COMMITTER_DATE: date,
    GIT_CONFIG_NOSYSTEM: "1",
    HOME: here,
  };
  const r = spawnSync(
    "git",
    ["-c", "commit.gpgsign=false", "-c", "core.autocrlf=false", "-c", "index.version=2", ...args],
    { cwd: app, env, encoding: "utf8" }
  );
  if (r.status !== 0) throw new Error(`git ${args.join(" ")} failed: ${r.stderr}`);
  return r.stdout.trim();
}

